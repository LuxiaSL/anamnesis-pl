"""Build replay rows for posttraining's per-turn-labelled tsumugi curation scenes (base-weights subset).

Inputs: a curation record directory holding ``sample.json`` (``{"scenes": [{"id", "header", "turns":
[{"speaker", "text"}]}]}``) and ``turn-labels.jsonl`` (one row per turn: ``id`` = scene id, ``turn``,
``coherent``, ``in_character``, ``seed_use``, ``tag``, ``speaker``, ``text``, ``verdict``, ``source``,
``n_turns_scene``).

Only turns generated by the release base weights are kept (sources ``assembled``, ``r1``, ``r1x``,
``eval-base`` by default); other sources are counted and skipped.

Context: what the loom showed the model when it wrote turn ``i``, using kotodama's own code:

  seen    = window_turns(turns[:i], header, n_seed=0, window_chars=W[source])
  context = render_prompt(Transcript(seen, header), turns[i].speaker)    # ends "\\n\\n<Name>:"
  full    = context + " " + turns[i].text

Each kept turn becomes one replay row:

  input_ids     = tokenize(full)   (one pass over the whole string, as the server tokenizes a prompt)
  prompt_length = the token index where the context ends   (span = input_ids[prompt_length:], the turn's tokens)

The prompt length is ``len(tokenize(context))`` when that is a prefix of ``input_ids``. Otherwise (a
re-segmentation at or before the boundary) the row is kept only if some token boundary of
``input_ids`` decodes to exactly ``context``, found by bisection as posttraining's steer grower finds
its span starts; with no exact boundary (a token that straddles the context/turn seam) the row is
skipped and counted.

``assembled`` scenes were cleaned after generation, so their context is approximate
(``cleaned_source: true`` on the row).

``cand_id`` is deterministic: ``curation:<scene id>:t<turn:03d>``.

Output: a JSONL with a header row (``_header: true``) and one row per turn, in the shape
``sign_koto_replay_rows.py`` reads (labels ride as top-level row fields, as the msteer rows carry
theirs).
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Any, Optional

DEFAULT_SOURCES: tuple[str, ...] = ("assembled", "r1", "r1x", "eval-base")
CLEANED_SOURCES: frozenset[str] = frozenset({"assembled"})
# window_chars per source, with where each value was read (the loom runs' run.json, config.window_chars)
DEFAULT_WINDOW: dict[str, tuple[int, str]] = {
    "assembled": (11000, "/mnt/beegfs/luxia/posttrain-tsumugi/r1-anthology/full/run.json"),
    "r1": (11000, "/mnt/beegfs/luxia/posttrain-tsumugi/r1/{loom,loom-b,loom-c,loom-d,node-run}/run.json (all 11000)"),
    "r1x": (11000, "/mnt/beegfs/luxia/posttrain-tsumugi/r1x/{pilot,pilot-ext,full}/run.json (all 11000)"),
    "eval-base": (11000, "node2 /models/luxia/kotodama/posttrain/runs/r1-dpo-momentum-eval/scenes/base/probe0/run.json"),
}
LABEL_FIELDS: tuple[str, ...] = ("coherent", "in_character", "seed_use", "tag", "verdict", "source", "speaker",
                                 "n_turns_scene")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def cand_id(scene_id: str, turn: int) -> str:
    return f"curation:{scene_id}:t{turn:03d}"


def char_boundary(tok: Any, ids: list[int], text: str, char: int) -> Optional[int]:
    """The token index k with ``decode(ids[:k]) == text[:char]``, or None (posttraining's span_start)."""
    lo, hi = 0, len(ids)
    while lo < hi:
        mid = (lo + hi) // 2
        if len(tok.decode(ids[:mid])) < char:
            lo = mid + 1
        else:
            hi = mid
    return lo if tok.decode(ids[:lo]) == text[:char] else None


def parse_windows(specs: list[str]) -> dict[str, tuple[int, str]]:
    out = dict(DEFAULT_WINDOW)
    for spec in specs:
        name, sep, val = spec.partition("=")
        if not sep:
            raise ValueError(f"--window wants source=W, got {spec!r}")
        out[name] = (int(val), "command line")
    return out


def load_labels(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open() as fh:
        for n, line in enumerate(fh, 1):
            if not line.strip():
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{n}: bad JSON: {exc}") from exc
            if not isinstance(rec.get("turn"), int) or not isinstance(rec.get("id"), str):
                continue  # scene summary rows ("turn": "scene") or malformed
            rows.append(rec)
    return rows


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", required=True, type=Path, help="curation record dir (sample.json, turn-labels.jsonl)")
    ap.add_argument("--out", required=True, type=Path, help="replay-rows JSONL to write")
    ap.add_argument("--kotodama-src", type=Path, default=Path.home() / "projects/kotodama/src",
                    help="kotodama src/ to import transcript/loom/presets from")
    ap.add_argument("--sources", default=",".join(DEFAULT_SOURCES), help="comma list of sources to keep")
    ap.add_argument("--window", action="append", default=[], metavar="SOURCE=W",
                    help="override a source's window_chars")
    args = ap.parse_args(argv)

    sample_path, labels_path = args.src / "sample.json", args.src / "turn-labels.jsonl"
    for p in (sample_path, labels_path):
        if not p.exists():
            print(f"REFUSED: {p} missing", file=sys.stderr)
            return 2
    if not (args.kotodama_src / "kotodama").is_dir():
        print(f"REFUSED: no kotodama package under {args.kotodama_src}", file=sys.stderr)
        return 2
    sys.path.insert(0, str(args.kotodama_src))
    os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
    from kotodama import presets
    from kotodama.posttrain.loom import window_turns
    from kotodama.posttrain.transcript import Transcript, Turn, render_prompt
    from transformers import AutoTokenizer

    keep = [s.strip() for s in args.sources.split(",") if s.strip()]
    windows = parse_windows(args.window)
    missing_w = [s for s in keep if s not in windows]
    if missing_w:
        print(f"REFUSED: no window_chars for sources {missing_w}", file=sys.stderr)
        return 2

    tok = AutoTokenizer.from_pretrained(presets.TOKENIZER_NAME)
    probe = "Ann: hello\n\nBob:"
    if tok.encode(probe) != tok.encode(probe, add_special_tokens=False):
        print("REFUSED: tokenizer adds special tokens; the server's prompt ids carry none", file=sys.stderr)
        return 2

    scenes: dict[str, dict[str, Any]] = {s["id"]: s for s in json.loads(sample_path.read_text())["scenes"]}
    labels = load_labels(labels_path)

    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    counts: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    by_coherent: collections.Counter = collections.Counter()
    for lab in labels:
        src, sid, i = str(lab.get("source")), lab["id"], int(lab["turn"])
        c = counts[src]
        if src not in keep:
            c["skipped_other_weights"] += 1
            continue
        scene = scenes.get(sid)
        if scene is None:
            c["skipped_no_scene"] += 1
            continue
        turns_raw = scene["turns"]
        if not 0 <= i < len(turns_raw):
            c["skipped_turn_out_of_range"] += 1
            continue
        if turns_raw[i]["text"] != lab["text"] or turns_raw[i]["speaker"] != lab["speaker"]:
            c["skipped_text_mismatch"] += 1
            continue
        header = scene.get("header", "") or ""
        W, _ = windows[src]
        turns = tuple(Turn(t["speaker"], t["text"]) for t in turns_raw)
        prior = turns[:i]
        seen_turns = window_turns(prior, header, 0, W)
        context = render_prompt(Transcript(seen_turns, header), turns[i].speaker)
        full = context + " " + turns[i].text
        ids = tok.encode(full, add_special_tokens=False)
        ctx_ids = tok.encode(context, add_special_tokens=False)
        prefix_ok = ids[:len(ctx_ids)] == ctx_ids
        if prefix_ok:
            P = len(ctx_ids)
        else:
            c["prefix_mismatch"] += 1
            P = char_boundary(tok, ids, full, len(context))
            if P is None:
                c["skipped_boundary_merge"] += 1
                continue
            c["prefix_mismatch_recovered"] += 1
        if not 0 < P < len(ids):
            c["skipped_empty_span"] += 1
            continue
        cid = cand_id(sid, i)
        if cid in seen:
            raise ValueError(f"duplicate cand_id {cid}")
        seen.add(cid)
        windowed = len(seen_turns) < len(prior)
        row: dict[str, Any] = dict(
            cand_id=cid, input_ids=ids, prompt_length=P, n_tokens=len(ids) - P,
            scene_id=sid, turn=i,
            **{k: lab.get(k) for k in LABEL_FIELDS},
            windowed=windowed, cleaned_source=src in CLEANED_SOURCES, window_chars=W,
            n_context_turns=len(seen_turns), n_prior_turns=len(prior), context_chars=len(context),
            n_chars=len(turns[i].text), prefix_ok=prefix_ok,
        )
        rows.append(row)
        c["rows"] += 1
        c["windowed"] += int(windowed)
        by_coherent[str(lab.get("coherent"))] += 1

    header = dict(
        _header=True, version="curation-turn-rows-v1",
        source=str(labels_path), source_sha256=sha256_file(labels_path),
        sample=str(sample_path), sample_sha256=sha256_file(sample_path),
        kotodama_src=str(args.kotodama_src), tokenizer=presets.TOKENIZER_NAME,
        sources=keep, window_chars={s: {"W": windows[s][0], "from": windows[s][1]} for s in keep},
        construction=("context = render_prompt(Transcript(window_turns(turns[:i], header, 0, W), header), "
                      "turns[i].speaker); input_ids = tokenize(context + ' ' + turns[i].text) (no special "
                      "tokens); prompt_length = len(tokenize(context)) when a prefix, else the exact char "
                      "boundary by bisection, else skipped; span = the turn's tokens. assembled scenes were "
                      "cleaned after generation: context approximate (cleaned_source)."),
        cand_id="curation:<scene id>:t<turn:03d>",
        counts={s: dict(c) for s, c in sorted(counts.items())},
        by_coherent=dict(sorted(by_coherent.items())),
        n_rows=len(rows),
        max_len=max((len(r["input_ids"]) for r in rows), default=0),
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.out.with_suffix(args.out.suffix + ".tmp")
    with tmp.open("w") as fh:
        fh.write(json.dumps(header) + "\n")
        for r in rows:
            fh.write(json.dumps(r) + "\n")
    tmp.replace(args.out)
    print(json.dumps({k: header[k] for k in ("counts", "by_coherent", "n_rows", "max_len")}, indent=1))
    print(f"wrote {len(rows)} rows to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
