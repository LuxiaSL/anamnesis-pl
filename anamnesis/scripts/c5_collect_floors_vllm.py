"""Computer #5 install-lever PoC — S1 (vLLM): collect floor generations. BANK OF RECORD.

SPEC: research/planning/SPEC-computer5-install-lever-poc-2026-07-28.md §3 (S1), §6 (G2).
vLLM twin of `c5_collect_floors.py` (HF). Same prompts, same sampling law, same jsonl schema.

⚠ ONE ENGINE FOR ALL DONORS — NON-NEGOTIABLE.
The construction reads Delta = mu(c5 gen-means) - mu(base gen-means) and attributes the
difference to the MODEL. If base floors were generated by HF and c5 floors by vLLM, any
engine-induced difference in sampling numerics, RNG, or stop handling lands inside Delta and is
indistinguishable from persona. So every donor's floors come from THIS script or none do.
(The HF banks from the first pass are retained as an engine-comparison reference only, never
mixed into a vector.)

WHY vLLM: generation is the dominant cost of the whole plan. Measured HF throughput on 2xB200
at 70B/bf16/batch-8 was ~80 gens per 217s. S1 tolerates that; S7's dose ladder (thousands of
generations) does not.

ENV: run under a conda env that ships vLLM — READ-ONLY, nothing installed, nothing modified.
    /home/cluster-user/miniconda/envs/blackwell/bin/python   (vllm 0.16.0, torch 2.9.1)
Never pip/conda install into these envs: they are shared and ENABLE_USER_SITE=True means a
stray user-site install silently poisons every other env on the box.

Stop-token note: vLLM excludes the stop string from the output by default; HF's `stop_strings`
includes it. Immaterial here — the state extractor trims at the first stop marker either way —
but the banks are NOT byte-identical across engines and must not be interleaved.
"""
from __future__ import annotations

import argparse
import json
import logging
import os
import statistics
import sys
import time
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

# Computer's native sampling (README) — NOT the HF generation_config defaults (0.6/0.9).
TEMPERATURE = 1.0
TOP_P = 0.98
STOP_SEQUENCE = "\n\n**User:**"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model-path", required=True)
    ap.add_argument("--label", required=True, help="roster label: base / c5 / c2 / lora64 / lora512")
    ap.add_argument("--lora-path", default=None,
                    help="LoRA donor. vLLM applies it via LoRARequest (no merge, no disk write).")
    ap.add_argument("--prompts", type=Path, required=True)
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--arm", default="substantive",
                    help="G2 VERDICT 2026-07-29: 'substantive'. The naive ('hello') arm gave base "
                         "a median of 5 completion tokens — koto's aphasia failure reproduced.")
    ap.add_argument("--n-samples", type=int, default=8)
    ap.add_argument("--max-new-tokens", type=int, default=200)
    ap.add_argument("--max-model-len", type=int, default=768,
                    help="prompt (~120) + completion (<=200) + margin. Kept small on purpose: "
                         "less KV cache reserved = faster startup, and we never need long context.")
    ap.add_argument("--tp", type=int, default=2, help="tensor-parallel size; must equal visible GPUs")
    ap.add_argument("--gpu-mem-util", type=float, default=0.90)
    ap.add_argument("--seed", type=int, default=20260729)
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()

    visible = os.environ.get("CUDA_VISIBLE_DEVICES")
    if visible:
        n_vis = len([x for x in visible.split(",") if x.strip()])
        if n_vis != args.tp:
            sys.exit(f"FATAL: --tp {args.tp} but CUDA_VISIBLE_DEVICES has {n_vis} GPUs ({visible}). "
                     "Heimdall sets that variable; match --tp to --gpus.")

    if not args.prompts.is_file():
        sys.exit(f"FATAL: prompt set not found: {args.prompts}")
    ps = json.loads(args.prompts.read_text(encoding="utf-8"))
    prompts = [p for p in ps["prompts"] if p["arm"] == args.arm]
    if not prompts:
        sys.exit(f"FATAL: no prompts with arm={args.arm!r}")
    if args.limit:
        prompts = prompts[: args.limit]

    args.out_dir.mkdir(parents=True, exist_ok=True)
    out_path = args.out_dir / f"floors_{args.label}.jsonl"
    if out_path.exists():
        sys.exit(f"FATAL: {out_path} exists — refusing to overwrite a bank. Move it or relabel.")

    try:
        from vllm import LLM, SamplingParams
    except ImportError as exc:
        sys.exit(f"FATAL: vllm unavailable — run under the blackwell conda env: {exc}")

    llm_kwargs = dict(
        model=args.model_path, tensor_parallel_size=args.tp, dtype="bfloat16",
        max_model_len=args.max_model_len, gpu_memory_utilization=args.gpu_mem_util,
        seed=args.seed, trust_remote_code=False,
    )
    lora_request = None
    if args.lora_path:
        # LoRA donors ride the SAME resident base — no 132G merge, no extra disk.
        from vllm.lora.request import LoRARequest
        llm_kwargs["enable_lora"] = True
        llm_kwargs["max_lora_rank"] = 512  # lora512 is the largest donor
        lora_request = LoRARequest("donor", 1, args.lora_path)

    logger.info("loading %s (tp=%d, lora=%s)", args.model_path, args.tp, args.lora_path)
    llm = LLM(**llm_kwargs)

    sampling = SamplingParams(
        n=args.n_samples, temperature=TEMPERATURE, top_p=TOP_P,
        max_tokens=args.max_new_tokens, stop=[STOP_SEQUENCE], seed=args.seed,
    )

    texts = [p["prompt_text"] for p in prompts]
    t0 = time.time()
    gen_kwargs = {"lora_request": lora_request} if lora_request else {}
    # use_tqdm=False explicitly: vLLM 0.16 computes a throughput line as
    # total_in_toks / pbar.format_dict["elapsed"], which is a ZeroDivisionError whenever the
    # bar is a no-op (e.g. TQDM_DISABLE=1). Generation completes and the crash lands AFTER,
    # silently costing the whole run. Turning the bar off at the call site avoids the path.
    outputs = llm.generate(texts, sampling, use_tqdm=False, **gen_kwargs)
    elapsed = time.time() - t0

    n_rows = n_empty = 0
    lens: list[int] = []
    n_tok_generated = 0
    with out_path.open("w", encoding="utf-8") as fh:
        for p, req in zip(prompts, outputs):
            prompt_ids = list(req.prompt_token_ids)
            for si, comp in enumerate(req.outputs):
                comp_ids = list(comp.token_ids)
                # Empty completions are VALID (Computer passes the floor); banked, not retried.
                fh.write(json.dumps({
                    "model": args.label, "engine": "vllm", "prompt_id": p["prompt_id"],
                    "arm": p["arm"], "topic": p["topic"], "sample_idx": si, "seed": args.seed,
                    "prompt_ids": prompt_ids, "completion_ids": comp_ids,
                    "text": comp.text, "n_completion_tokens": len(comp_ids),
                    "finish_reason": comp.finish_reason, "stop_reason": str(comp.stop_reason),
                }) + "\n")
                n_rows += 1
                n_empty += int(len(comp_ids) == 0)
                lens.append(len(comp_ids))
                n_tok_generated += len(comp_ids)

    stats = {
        "model": args.label, "engine": "vllm", "arm": args.arm, "n_rows": n_rows,
        "n_empty": n_empty, "elapsed_s": round(elapsed, 1),
        "throughput_tok_per_s": round(n_tok_generated / max(elapsed, 1e-9), 1),
        "median_tokens": statistics.median(lens) if lens else 0,
        "mean_tokens": round(statistics.fmean(lens), 1) if lens else 0.0,
        "total_completion_tokens": n_tok_generated,
    }
    (args.out_dir / f"floorstats_{args.label}.json").write_text(json.dumps(stats, indent=1))
    logger.info("FLOOR STATS %s", json.dumps(stats))
    logger.info("wrote %d rows (%d empty) -> %s", n_rows, n_empty, out_path)


if __name__ == "__main__":
    main()
