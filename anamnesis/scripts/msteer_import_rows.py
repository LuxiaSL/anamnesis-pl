"""Build serving-drain import rows for the momentum-steer worn-vs-unworn read (phase 2).

Inputs:
  --growth    posttraining's ``growth.jsonl`` (one row per (context_index, arm), with ``descendants``)
  --ids       its ``ids.jsonl`` (``context_ids`` per context_index: the server's prompt ids)
  --payloads  pleroma's ``fixdose_v1/payloads.json`` (the injections actually worn; ``payloads[name].injection``)

Each depth-1 descendant with ``completion_ids`` becomes import rows for
``python -m kotodama.serve.sign --import_rows``:

  ids           = context_ids + completion_ids   (the generated bytes, not a re-tokenisation)
  prompt_length = len(context_ids)               (under steer_span=decode the lever covers exactly the
                                                  generated tokens)

A lever arm (its growth cell names a payload with an injection) gives two rows on the same ids:
``<cid>.worn`` with that payload's injection, and ``<cid>.unworn`` with ``injection: null``. Arms
without an injection (the unworn arm, the samplers) give one row, ``<cid>.unworn``. The join is on the
growth cell's ``payload`` field, so R arms pick up their per-context R{c%3} payload.

``cid`` is ``msteer:c<context_index:03d>:<arm>:s<slot>``, as in ``msteer_replay_rows.py``.
Depth-2 replies are skipped: their context is a re-tokenised next_context_ids, so they would not be
the generation's bytes.
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import json
from pathlib import Path
from typing import Any


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open() as fh:
        return [json.loads(line) for line in fh if line.strip()]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--growth", required=True, type=Path)
    ap.add_argument("--ids", required=True, type=Path)
    ap.add_argument("--payloads", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args(argv)

    payloads: dict[str, dict[str, Any]] = json.loads(args.payloads.read_text())["payloads"]
    contexts: dict[int, list[int]] = {}
    for rec in read_jsonl(args.ids):
        ci = int(rec["context_index"])
        if ci in contexts:
            raise SystemExit(f"duplicate context_index {ci} in {args.ids}")
        contexts[ci] = [int(t) for t in rec["context_ids"]]

    counts: collections.Counter[str] = collections.Counter()
    seen: set[str] = set()
    out_rows: list[dict[str, Any]] = []
    for cell in read_jsonl(args.growth):
        if cell.get("_header"):
            continue
        ci, arm, pname = int(cell["context_index"]), str(cell["arm"]), cell.get("payload")
        span = (cell.get("wear") or {}).get("steer_span", "decode")
        if span != "decode":
            raise SystemExit(f"c{ci} {arm}: steer_span {span!r}; this builder assumes decode")
        injection = None
        if pname is not None and pname in payloads:
            injection = payloads[pname].get("injection")
            rule = (injection or {}).get("rule", "S")
            if injection is not None and rule == "N":
                raise SystemExit(f"payload {pname} is rule N, which the drain refuses")
        elif pname not in (None, "unworn", arm):
            raise SystemExit(f"c{ci} {arm}: payload {pname!r} not in {args.payloads}")
        if ci not in contexts:
            raise SystemExit(f"context_index {ci} missing from {args.ids}")
        ctx = contexts[ci]
        for d in cell["descendants"]:
            if int(d.get("depth", 0)) != 1:
                counts["skip_depth2"] += 1
                continue
            comp = d.get("completion_ids")
            if not comp:
                counts["skip_no_completion"] += 1
                continue
            cid = f"msteer:c{ci:03d}:{arm}:s{int(d['slot'])}"
            meta = dict(context_index=ci, arm=arm, payload=pname, slot=int(d["slot"]),
                        node_id=cell.get("node_id"), ended_by=d.get("ended_by"), n_completion=len(comp))
            base = dict(ids=ctx + [int(t) for t in comp], prompt_length=len(ctx), steer_span="decode")
            variants = [("worn", injection), ("unworn", None)] if injection is not None else [("unworn", None)]
            for tag, inj in variants:
                rid = f"{cid}.{tag}"
                if rid in seen:
                    raise SystemExit(f"duplicate id {rid}")
                seen.add(rid)
                out_rows.append(dict(id=rid, **base, injection=inj, meta=dict(meta, wear=tag)))
                counts[f"rows_{tag}"] += 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w") as fh:
        for r in out_rows:
            fh.write(json.dumps(r) + "\n")
    summary = dict(out=str(args.out), out_sha256=sha256_file(args.out),
                   growth_sha256=sha256_file(args.growth), ids_sha256=sha256_file(args.ids),
                   payloads_sha256=sha256_file(args.payloads), **counts)
    args.out.with_suffix(".summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps(summary))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
